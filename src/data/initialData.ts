export function computeRfmSegment(recencyDays: number, totalVisits: number, totalSpendCAD: number): {
  rScore: number;
  fScore: number;
  mScore: number;
  segment: RfmSegment;
} {
  // Recency Score (1-5) where lower days = higher score
  let rScore = 1;
  if (recencyDays <= 20) rScore = 5;
  else if (recencyDays <= 45) rScore = 4;
  else if (recencyDays <= 90) rScore = 3;
  else if (recencyDays <= 180) rScore = 2;
  else rScore = 1;

  // Frequency Score (1-5)
  let fScore = 1;
  if (totalVisits >= 9) fScore = 5;
  else if (totalVisits >= 6) fScore = 4;
  else if (totalVisits >= 4) fScore = 3;
  else if (totalVisits >= 2) fScore = 2;
  else fScore = 1;

  // Monetary Score (1-5)
  let mScore = 1;
  if (totalSpendCAD >= 1200) mScore = 5;
  else if (totalSpendCAD >= 800) mScore = 4;
  else if (totalSpendCAD >= 500) mScore = 3;
  else if (totalSpendCAD >= 250) mScore = 2;
  else mScore = 1;

  // Segment logic based on RFM standard matrix
  let segment: RfmSegment = 'Recent Customers';

  if (rScore >= 4 && fScore >= 4 && mScore >= 4) {
    segment = 'Champions';
  } else if (rScore >= 3 && fScore >= 3 && mScore >= 3) {
    segment = 'Loyal Customers';
  } else if (rScore >= 4 && fScore <= 2 && mScore >= 3) {
    segment = 'Potential Loyalists';
  } else if (rScore >= 4 && fScore <= 2) {
    segment = 'Recent Customers';
  } else if (rScore === 3 && fScore <= 3 && mScore >= 3) {
    segment = 'Promising';
  } else if (rScore === 3 && fScore >= 3) {
    segment = 'Needs Attention';
  } else if (rScore <= 2 && fScore >= 3 && mScore >= 3) {
    segment = "Can't Lose Them";
  } else if (rScore <= 2 && fScore >= 2) {
    segment = 'At Risk';
  } else {
    segment = 'Hibernating';
  }

  return { rScore, fScore, mScore, segment };
}

